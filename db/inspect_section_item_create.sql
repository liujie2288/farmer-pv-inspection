-- ============================================================
-- 巡检小项表 (64条检查项)
-- item_type: 1=正常/异常选择, 2=实测值填写, 3=照片上传
-- ============================================================
CREATE TABLE `inspect_section_item` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `section_id` BIGINT NOT NULL COMMENT '所属大项ID(关联inspect_section.id)',
  `item_no` TINYINT(4) unsigned NOT NULL COMMENT '小项序号(大项内，仅展示/排序用)',
  `item_type` TINYINT NOT NULL DEFAULT 1 COMMENT '事项类型: 1正常/异常 2实测值 3照片',
  `category` VARCHAR(20) DEFAULT NULL COMMENT '类别(基础/支架/电缆/采集装置等)',
  `content` VARCHAR(500) NOT NULL COMMENT '巡检内容',
  `create_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_section_item` (`section_id`, `item_no`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='巡检小项表';

